const STORAGE_LANG_KEY = 'aurapalm_lang';

export function getLanguage() {
  return localStorage.getItem(STORAGE_LANG_KEY) || 'en';
}

export function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'hi') lang = 'en';
  localStorage.setItem(STORAGE_LANG_KEY, lang);
  document.documentElement.setAttribute('lang', lang);
  applyTranslations(lang);
  updateLanguageToggles(lang);
}

export function updateLanguageToggles(lang) {
  const toggles = document.querySelectorAll('.lang-toggle-btn');
  toggles.forEach(btn => {
    btn.innerHTML = lang === 'en' 
      ? `<span class="lang-code active">EN</span><span class="lang-sep">|</span><span class="lang-code">हिं</span>`
      : `<span class="lang-code">EN</span><span class="lang-sep">|</span><span class="lang-code active">हिं</span>`;
    btn.setAttribute('title', lang === 'en' ? 'Switch to Hindi / हिन्दी में बदलें' : 'Switch to English');
    btn.setAttribute('aria-label', 'Toggle language');
  });
}

export function applyTranslations(lang) {
  const dict = translations[lang] || translations.en;
  
  // Update all elements with data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = getNestedValue(dict, key);
    if (value) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', value);
      } else {
        el.innerHTML = value;
      }
    }
  });

  // Dispatch global event for custom components
  window.dispatchEvent(new CustomEvent('aurapalm:langchange', { detail: { lang, dict } }));
}

function getNestedValue(obj, path) {
  return path.split('.').reduce((acc, part) => acc && acc[part], obj);
}

// Auto init on module load
if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = getLanguage();
    setLanguage(currentLang);

    // Bind all lang-toggle-btn clicks
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const nextLang = getLanguage() === 'en' ? 'hi' : 'en';
        setLanguage(nextLang);
        if (window.showToast) {
          window.showToast(nextLang === 'hi' ? 'भाषा बदलकर हिन्दी कर दी गई है।' : 'Language switched to English.');
        }
      });
    });
  });
}

window.aurapalmSetLanguage = setLanguage;
window.aurapalmGetLanguage = getLanguage;
